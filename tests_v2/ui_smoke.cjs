/* Run against an isolated --serve workspace. Uses no API key or live model. */
const fs = require('fs');
const assert = require('assert');
const { chromium } = require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES ? process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES + '/playwright' : 'playwright');
(async()=>{
  const runtime=JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('status of 400'))errors.push(m.text());});
  await page.goto(`http://127.0.0.1:${runtime.port}/#${runtime.token}`);
  await page.getByRole('button',{name:'Start a repair',exact:false}).click();
  const dialog=page.getByRole('dialog');
  await dialog.locator('[name=title]').fill('Synthetic bench validation');
  await dialog.locator('[name=device]').fill('Test board');
  await dialog.locator('[name=board_id]').fill('TEST-001');
  await dialog.locator('[name=revision]').fill('A');
  await dialog.locator('[name=symptom]').fill('Synthetic no-power case for interface testing. No customer board.');
  await dialog.getByRole('button',{name:'Open repair',exact:true}).click();
  await page.getByRole('heading',{name:'Synthetic bench validation',exact:true}).waitFor();
  await page.getByRole('button',{name:'Record reading',exact:false}).click();
  await page.locator('#quick-reading').fill('USB_D+ = -420 mV');
  await dialog.getByRole('button',{name:'Fill fields'}).click();
  await page.waitForFunction(()=>document.querySelector('[name=value]')?.value==='-0.42');
  await dialog.locator('[name=power_state]').selectOption('standby');
  await dialog.locator('[name=reference]').fill('Board ground');
  await dialog.getByRole('button',{name:'Save reading',exact:true}).click();
  await page.locator('#readings').getByText('-0.42 V',{exact:true}).waitFor();
  await page.getByRole('tab',{name:'Files & photos',exact:false}).click();
  await page.getByRole('button',{name:'Add files or photos',exact:false}).click();
  await dialog.locator('[name=role]').selectOption('boardview');
  await dialog.locator('[name=files]').setInputFiles({name:'synthetic.csv',mimeType:'text/csv',buffer:Buffer.from('ref,pin,net,side,x,y\nU1,1,USB_D+,T,1,2\nU1,2,USB_D-,T,3,4\n')});
  await dialog.locator('[name=scope_confirmed]').check();
  await dialog.getByRole('button',{name:'Import files',exact:true}).click();
  await page.locator('#source-list').getByText('parsed',{exact:true}).waitFor();
  await page.getByRole('tab',{name:'Bench',exact:true}).click();
  await page.locator('#lookup-query').fill('USB_D-');
  await page.locator('#lookup-form button').click();
  await page.locator('#lookup-results').getByText('U1.2 → USB_D-',{exact:true}).waitFor();
  // Ensure polling doesn't destroy evidence controls or their backing registry.
  await page.waitForTimeout(2400);
  await page.locator('#lookup-results').getByRole('button',{name:'View pin details'}).click();
  await dialog.locator('.pin-connection strong').getByText('USB_D-', {exact:true}).waitFor();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.locator('#question').fill('What should I check next?');
  await page.getByRole('button',{name:'Find the next step',exact:false}).click();
  await page.locator('#jobs').getByText('Add your OpenAI API key', {exact:false}).waitFor();
  assert.equal(await page.locator('#question').inputValue(),'What should I check next?');
  await page.getByRole('button',{name:'Settings & equipment'}).click();
  await dialog.locator('[name=monthly_limit]').fill('75');
  await dialog.getByRole('button',{name:'Save settings'}).click();
  await page.waitForFunction(()=>!document.querySelector('dialog').open);
  await page.reload();
  await page.getByRole('heading',{name:'Synthetic bench validation',exact:true}).waitFor();
  assert.equal(await page.locator('#question').inputValue(),'What should I check next?');
  await page.getByRole('button',{name:'Record outcome'}).click();
  await dialog.locator('[name=fix]').fill('Synthetic connector replacement');
  await dialog.locator('[name=verification]').fill('Synthetic repeated cold boots and load tests passed');
  await dialog.locator('[name=technician_confirmed]').check();
  await dialog.getByRole('button',{name:'Save outcome'}).click();
  await page.locator('#case-status').getByText('Repair confirmed',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Reopen repair',exact:true}).click();
  await page.locator('#case-status').getByText('open',{exact:true}).waitFor();
  await page.getByRole('tab',{name:'Timeline',exact:true}).click();
  await page.getByRole('button',{name:'Retract incorrect entry',exact:true}).click();
  await page.locator('#timeline').getByText('Retracted',{exact:false}).waitFor();
  await page.getByRole('tab',{name:'Bench',exact:true}).click();
  const out=process.argv[3];if(out)await page.screenshot({path:out,fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Browser workflow passed: create, reading, file import, exact lookup, missing-key recovery, settings, reload, outcome, reopen, correction.');
})().catch(error=>{console.error(error);process.exit(1);});
